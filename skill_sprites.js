// スキルアイコンをCanvasに描画して返す
function makeSkillIcon(id, scale = 1) {
  const rows = SKILL_SPRITES[id];
  const cv = document.createElement('canvas');
  cv.width = 16 * scale; cv.height = 16 * scale;
  const ctx = cv.getContext('2d');
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      const col = SKILL_PALETTE[row[x]];
      if (!col) continue;
      ctx.fillStyle = col;
      ctx.fillRect(x * scale, y * scale, scale, scale);
    }
  });
  return cv;
}

function skillIconHtml(id, size = 32) {
  return `<img src="${makeSkillIcon(id, 4).toDataURL()}" width="${size}" height="${size}" style="image-rendering:pixelated;vertical-align:middle">`;
}
